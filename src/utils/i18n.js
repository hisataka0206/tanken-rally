// クエリ・ハッシュから言語を判定
//
// ポリシー:
//   - 末尾なし／?lang=elementary/kids/easy → 'elementary'（子供版がデフォルト）
//   - ?lang=original / ?lang=ja           → 'ja'（大人向け通常版）
//   - ?lang=en / ?lang=english             → 'en'（英語版）
//
// 背景: アプリの主たる利用者層が小学生のため、デフォルトを elementary に切替。
// 大人向けの通常版は明示的に ?lang=original を指定して開く。
export function getLangFromUrl() {
  const params = new URLSearchParams(location.search);
  let raw = params.get('lang');
  if (!raw && location.hash) raw = location.hash.replace(/^#/, '');
  const lower = (raw || '').trim().toLowerCase();
  if (lower === 'en' || lower === 'english') return 'en';
  if (lower === 'original' || lower === 'ja' || lower === 'standard' || lower === 'adult') return 'ja';
  // 未指定 / elementary / kids / easy / その他 → 子供版がデフォルト
  return 'elementary';
}

export const LANG = getLangFromUrl();

// 翻訳取得
export function t(key, fallback) {
  const dict = TRANSLATIONS[LANG] || TRANSLATIONS.ja;
  if (dict[key] !== undefined) return dict[key];
  if (TRANSLATIONS.ja[key] !== undefined) return TRANSLATIONS.ja[key];
  return fallback !== undefined ? fallback : key;
}

// ===== ふりがな（ルビ）変換 =====
// 「（）」には2種類あり、扱いを分ける（混ぜない）：
//   (A) ふりがな＝読み: 漢字の直後の（ひらがなだけ）… これだけを <ruby> で漢字の上に小さく表示する。
//        例「育（そだ）てる」「思（おも）い出（だ）す」「上位（じょうい）」→ ルビ化。
//   (B) 補足のカッコ: 上記以外（例「育てる（仮）」「（任意）」「（約60分）」「（パスワード入力）」）
//        … これは説明なので（）のまま残す。ルビにしない。
// 判定は「漢字の直後 ＋ 中身がひらがなのみ」＝読み、それ以外＝補足、で切り分ける。
//   ・入力欄の placeholder は属性なのでルビ化しない（applyI18n 側で除外）。
//   ・elementary（子ども版）のみ。大人向け ja / en では変換しない。
const _KANJI_RANGE = '\\u4E00-\\u9FFF\\u3400-\\u4DBF\\u3005\\u3007\\u30F6';
const _KANA_RANGE  = '\\u3041-\\u3096\\u309D\\u309E\\u30FC';
const _READ_RE = new RegExp('([' + _KANJI_RANGE + ']+)（([' + _KANA_RANGE + ']+)）', 'g');
/** ふりがな（読み）だけを <ruby> 化。補足カッコはそのまま。elementary のみ。
 *  対象がなければ null（textContent 経路のまま）。
 *  i18n文字列は内部固定の信頼済みコンテンツ（<strong>/<span> 等のHTMLを含む）ので、
 *  タグを壊さないよう HTMLエスケープはしない（ユーザー入力はここを通さない）。 */
export function furiganize(str) {
  if (LANG !== 'elementary') return null;
  if (typeof str !== 'string' || str.indexOf('（') === -1) return null;
  const out = str.replace(_READ_RE, '<ruby>$1<rt>$2</rt></ruby>');
  return out === str ? null : out;
}

// ===== 動的テキストのふりがな自動適用（DOM走査＋MutationObserver）=====
// applyI18n（data-i18n）以外に、JSで textContent/innerHTML に書き込まれた読みも
// ルビ表示にするための仕組み。テキストノードを走査し「漢字（かな）」を <ruby> の
// DOMノードへ置換する（innerHTML を使わず createTextNode で組むので XSS 安全）。
const _READ_PATTERN = '([' + _KANJI_RANGE + ']+)（([' + _KANA_RANGE + ']+)）';
const _READ_TEST = new RegExp(_READ_PATTERN);            // lastIndex を汚さない判定用
// ルビ化しない親要素（入力欄・選択肢・既存ルビ・スクリプト等）
const _SKIP_TAGS = { RUBY: 1, RT: 1, RP: 1, SCRIPT: 1, STYLE: 1, TEXTAREA: 1, OPTION: 1, SELECT: 1, TITLE: 1, INPUT: 1, CODE: 1 };

/** root 配下のテキストノードの「漢字（かな）」をルビ（<ruby><rt>）へ変換する。elementary のみ。 */
export function furiganizeNode(root) {
  if (LANG !== 'elementary' || !root || typeof document === 'undefined') return;
  const start = (root.nodeType === 3) ? root.parentNode : root;
  if (!start || start.closest && start.closest('[data-no-furigana]')) return;
  const walker = document.createTreeWalker(start, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const p = node.parentNode;
      if (!p || _SKIP_TAGS[p.nodeName]) return NodeFilter.FILTER_REJECT;
      const v = node.nodeValue;
      if (!v || v.indexOf('（') === -1 || !_READ_TEST.test(v)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const targets = [];
  let n;
  while ((n = walker.nextNode())) targets.push(n);
  targets.forEach(textNode => {
    const str = textNode.nodeValue;
    const frag = document.createDocumentFragment();
    const re = new RegExp(_READ_PATTERN, 'g');
    let last = 0, m;
    while ((m = re.exec(str)) !== null) {
      if (m.index > last) frag.appendChild(document.createTextNode(str.slice(last, m.index)));
      const ruby = document.createElement('ruby');
      ruby.appendChild(document.createTextNode(m[1]));
      const rt = document.createElement('rt');
      rt.appendChild(document.createTextNode(m[2]));
      ruby.appendChild(rt);
      frag.appendChild(ruby);
      last = m.index + m[0].length;
    }
    if (last < str.length) frag.appendChild(document.createTextNode(str.slice(last)));
    if (textNode.parentNode) textNode.parentNode.replaceChild(frag, textNode);
  });
}

let _furiObserver = null;
/** #app 等の配下に加わる動的テキストを監視して、随時ふりがなを適用する。elementary のみ・1回だけ設置。 */
export function installFuriganaObserver(root) {
  if (LANG !== 'elementary' || _furiObserver || typeof MutationObserver === 'undefined') return;
  const target = root || document.body;
  if (!target) return;
  furiganizeNode(target); // 既存の内容にも1回適用
  _furiObserver = new MutationObserver(muts => {
    for (const mut of muts) {
      mut.addedNodes && mut.addedNodes.forEach(node => {
        if (node.nodeType === 1) furiganizeNode(node);            // 要素
        else if (node.nodeType === 3) {                            // 直接追加されたテキスト
          const p = node.parentNode;
          if (p && !_SKIP_TAGS[p.nodeName] && node.nodeValue && node.nodeValue.indexOf('（') !== -1) furiganizeNode(p);
        }
      });
    }
  });
  _furiObserver.observe(target, { childList: true, subtree: true });
}

// data-i18n / data-i18n-html / data-i18n-placeholder / data-i18n-title を一括適用
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    const text = t(el.dataset.i18n);
    if (typeof text !== 'string') return;
    // <option>/<title> は子要素（<ruby>）を持てないので、ルビ化せず素のテキストにする。
    const noHtml = el.tagName === 'OPTION' || el.tagName === 'TITLE';
    const ruby = noHtml ? null : furiganize(text);
    if (ruby !== null) el.innerHTML = ruby; else el.textContent = text;
  });
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    const text = t(el.dataset.i18nHtml);
    if (typeof text === 'string') el.innerHTML = furiganize(text) || text;
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const text = t(el.dataset.i18nPlaceholder);
    if (typeof text === 'string') el.setAttribute('placeholder', text);
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    const text = t(el.dataset.i18nTitle);
    if (typeof text === 'string') el.setAttribute('title', text);
  });
  // アイコンのみのボタン用：画面には文字を出さず、読み上げ・ツールチップにだけ意味を残す
  root.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const text = t(el.dataset.i18nAria);
    if (typeof text !== 'string') return;
    const plain = text.replace(/[（(][ぁ-ゖ]+[）)]/g, '');   // 読み上げにルビ括弧は不要
    el.setAttribute('aria-label', plain);
    if (!el.hasAttribute('data-i18n-title')) el.setAttribute('title', plain);
  });
  // <html lang="..."> も切り替え（'elementary' は CSS では ja 扱い）
  document.documentElement.lang = LANG === 'elementary' ? 'ja' : LANG;
}

// Elementary（ひらがな）モードでは Google が返す移動時間を「子供の歩行ペース」に合わせて
// 約1.5倍に補正して表示する。スコア計算（calculateScore）では補正前の値を使うこと。
export const KIDS_TIME_FACTOR = 1.5;
export function adjustMinForKids(min) {
  const n = Number(min);
  if (!isFinite(n) || n <= 0) return min;
  return LANG === 'elementary' ? Math.max(1, Math.round(n * KIDS_TIME_FACTOR)) : min;
}

